
const fs = require('node:fs');
for(const target of ['out-site','out-admin','out-admingeral']){
  fs.mkdirSync(target,{recursive:true});
  for(const name of ['index.html','_redirects','_headers','robots.txt']){
    fs.writeFileSync(target+'/'+name,'Generated by simulation');
  }
  if(target !== 'out-admingeral') fs.writeFileSync(target+'/_worker.js', '');
}
