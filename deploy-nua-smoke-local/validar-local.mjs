import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {spawn, spawnSync} from 'node:child_process';

const base = path.dirname(fileURLToPath(import.meta.url));
const project = path.join(base, 'Projeto com espacos final');
fs.mkdirSync(path.join(project, 'node_modules', 'wrangler', 'bin'), {recursive:true});
const selected = ['site','admin','admingeral'];
const names = ['nuaborges','nuaborges-admin','admingeral'];
const files = ['wrangler.toml','wrangler.admin.toml','wrangler.admingeral.toml'];
const outputs = ['out-site','out-admin','out-admingeral'];
for (const ix of [0,1,2]) {
  fs.writeFileSync(path.join(project,files[ix]), 'name = "'+names[ix]+'"\npages_build_output_dir = "'+outputs[ix]+'"\n');
}
const hashes = files.map((name) => fs.readFileSync(path.join(project,name),'utf8'));
fs.writeFileSync(path.join(project, 'package.json'), JSON.stringify({name:'local-test',scripts:{
  'build:packages': 'node build.cjs', typecheck: 'node -e "process.exit(0)"', test: 'node -e "process.exit(0)"',
}}));
fs.writeFileSync(path.join(project,'build.cjs'), String.raw`
const fs = require('node:fs');
for(const target of ['out-site','out-admin','out-admingeral']){
  fs.mkdirSync(target,{recursive:true});
  for(const name of ['index.html','_redirects','_headers','robots.txt']){
    fs.writeFileSync(target+'/'+name,'Generated by simulation');
  }
  if(target !== 'out-admingeral') fs.writeFileSync(target+'/_worker.js', '');
}
console.log('Compilação simulada');
`);
fs.writeFileSync(path.join(project,'node_modules','wrangler','bin','wrangler.js'), String.raw`
const a = process.argv.slice(2);
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const name = a[a.indexOf('--project-name')+1];
const deploy = path.join('.wrangler', 'deploy');
const cfg = JSON.parse(fs.readFileSync(path.join(deploy,'config.json'),'utf8'));
assert.match(fs.readFileSync(path.resolve(deploy,cfg.configPath),'utf8'),new RegExp('name = "'+name+'"'));
assert.equal(a[a.indexOf('--branch')+1],'main');
assert.equal(a.includes('--config'),false);
assert.ok(fs.existsSync(path.join(a[2],'index.html')));
assert.equal(fs.existsSync('functions'),false);
if(process.env.DEPLOY_SMOKE_FAIL === name) { console.error('[ERROR] Upload interrompido (teste)'); process.exit(9); }
if(process.env.DEPLOY_SMOKE_PAUSE === name) {
  console.log('Esperando cancelamento');
  setInterval(()=>{},1000);
} else {
  console.log('Deployment complete! Take a peek over at https://e123.'+name+'.pages.dev');
}
`);
const settings = {
  project_dir:project, default_options:{target:'all',run_build:true,run_tests:true,open_browser:false},
};
fs.writeFileSync(path.join(base,'config.json'),JSON.stringify(settings));
fs.writeFileSync(path.join(base,'http-simulado.mjs'), String.raw`
globalThis.fetch = async (address) => {
  const url = new URL(address);
  if(!['nuaborges.com.br','admin.nuaborges.com.br','admingeral.pages.dev'].includes(url.hostname) && !url.hostname.startsWith('e123.')) {
    throw new Error('Unexpected HTTP target');
  }
  const status = process.env.DEPLOY_SMOKE_BAD === url.hostname ? 403 : 200;
  return {ok: status === 200, status, url: url.href};
};
`);
const command = ['--import',pathToFileURL(path.join(base,'http-simulado.mjs')).href,path.join(base,'orquestrador.mjs')];
function execute(args, env={}) {
  const processResult = spawnSync(process.execPath,[...command,...args],{
    env:{...process.env,...env},encoding:'utf8',timeout:20000,
  });
  assert.equal(processResult.error,undefined,processResult.error?.message);
  assert.equal(processResult.stderr,'');
  const events = processResult.stdout.trim().split('\n').map((line)=>JSON.parse(line));
  const result = events.at(-1);
  assert.equal(result.event,'done',processResult.stdout);
  if(result.logPath) {
    assert.ok(fs.existsSync(result.logPath),result.logPath);
    assert.equal(JSON.parse(fs.readFileSync(result.logPath.replace(/\.log$/,'.json'),'utf8')).status,result.status);
  }
  return result;
}
assert.equal(execute(['--mode','build']).status,'ok');
assert.equal(execute(['--plan','--reuse']).status,'ok');
const ok = execute(['--reuse','--tests']);
assert.equal(ok.status,'ok');
for(const key of selected) {
  assert.equal(ok.targets[key].state,'verified',JSON.stringify(ok,null,2));
  assert.equal(ok.targets[key].checks.length,2);
}
const warned = execute(['--reuse','--targets','admin'],{DEPLOY_SMOKE_BAD:'admin.nuaborges.com.br'});
assert.equal(warned.status,'warning');
assert.equal(warned.targets.admin.state,'warning');
const partial = execute(['--reuse'],{DEPLOY_SMOKE_FAIL:'nuaborges-admin'});
assert.equal(partial.status,'failed');
assert.equal(partial.targets.site.state,'verified');
assert.equal(partial.targets.admin.state,'unconfirmed');
assert.equal(partial.targets.admingeral.state,'waiting');
const retry = execute(['--reuse','--targets','admingeral']);
assert.equal(retry.targets.admingeral.state,'verified');
assert.equal(execute(['--mode','http','--targets','site']).status,'ok');
const cancelResult = await new Promise((resolve,reject) => {
  const child = spawn(process.execPath,[...command,'--reuse','--managed'],{
    env:{...process.env,DEPLOY_SMOKE_PAUSE:'nuaborges'},stdio:['pipe','pipe','pipe'],
  });
  let received = '';
  const timeout = setTimeout(()=>{child.stdin.end(); reject(new Error('Cancellation timed out'));},15000);
  child.once('error',reject);
  child.stdout.on('data',chunk=>{
    const previous = received;
    received += chunk.toString('utf8');
    if (!previous.includes('Esperando cancelamento') && received.includes('Esperando cancelamento')) {
      child.stdin.write('cancel\n');
    }
  });
  child.on('close',(code)=>{
    clearTimeout(timeout);
    assert.equal(code,130,received);
    resolve(received.trim().split('\n').map(JSON.parse).at(-1));
  });
});
assert.equal(cancelResult.status,'cancelled');
assert.equal(cancelResult.targets.site.state,'unconfirmed');
assert.deepEqual(fs.readdirSync(path.join(project,'.wrangler')),[]);
assert.deepEqual(files.map((name)=>fs.readFileSync(path.join(project,name),'utf8')),hashes);
fs.appendFileSync(path.join(project,'out-site','index.html'),'changed');
const stale = execute(['--plan','--reuse','--targets','site']);
assert.equal(stale.status,'failed');
assert.match(stale.error,/mudou/);
console.log('OK: build, plano, testes, três destinos, HTTP 403, publicação parcial, pendentes, cancelamento, pacote alterado e configs preservadas.');
